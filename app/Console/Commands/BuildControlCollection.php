<?php

namespace App\Console\Commands;

use App\Mock\OpenApi\ControlPlaneSpec;
use Illuminate\Console\Command;

/**
 * Writes postman/UniFi-Mock-Control.postman_collection.json from ControlPlaneSpec (FR-023).
 * It is a SEPARATE collection so the integration collection stays identical to UniFi's.
 */
class BuildControlCollection extends Command
{
    public const TARGET = 'postman/UniFi-Mock-Control.postman_collection.json';

    protected $signature = 'mock:build-control-collection';

    protected $description = 'Generate the Postman collection for the /__mock control plane';

    public function handle(): int
    {
        $items = [];
        foreach (ControlPlaneSpec::operations() as $op) {
            $query = array_map(fn ($k, $v) => ['key' => $k, 'value' => $v], array_keys($op['query'] ?? []), $op['query'] ?? []);
            $segments = array_values(array_filter(explode('/', $op['path'])));
            $request = [
                'method' => $op['method'],
                'header' => [['key' => 'Accept', 'value' => 'application/json']],
                'url' => [
                    'raw' => '{{controlBase}}'.$op['path'].($query ? '?'.implode('&', array_map(fn ($q) => $q['key'].'='.$q['value'], $query)) : ''),
                    'host' => ['{{controlBase}}'],
                    'path' => $segments,
                ] + ($query ? ['query' => $query] : []),
                'description' => $op['description'],
            ];
            if (isset($op['body'])) {
                $request['header'][] = ['key' => 'Content-Type', 'value' => 'application/json'];
                $request['body'] = ['mode' => 'raw', 'raw' => json_encode($op['body'], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES), 'options' => ['raw' => ['language' => 'json']]];
            }
            $items[] = [
                'name' => $op['summary'],
                'event' => [['listen' => 'test', 'script' => ['type' => 'text/javascript', 'exec' => [
                    "pm.test('status {$op['status']}', () => pm.response.to.have.status({$op['status']}));",
                ]]]],
                'request' => $request,
            ];
        }

        $collection = [
            'info' => [
                'name' => 'UniFi Mock — Control plane',
                'description' => 'The mock-only /__mock control plane. Not part of UniFi; needs no X-API-KEY; answers 404 when APP_ENV=production. Generated by `php artisan mock:build-control-collection`.',
                'schema' => 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
            ],
            'item' => $items,
            'variable' => [['key' => 'controlBase', 'value' => 'http://127.0.0.1:8091/__mock']],
        ];

        file_put_contents(base_path(self::TARGET), json_encode($collection, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)."\n");
        $this->info('Written '.self::TARGET.' ('.count($items).' requests).');

        return self::SUCCESS;
    }
}
